-- Borra todo para poder recrear la base desde cero (orden inverso por las claves foráneas).
-- Tablas de los ejercicios de estudio (ver docs/estudio-examen.md)
DROP TABLE IF EXISTS ticket_repuestos;
DROP TABLE IF EXISTS valoraciones;
DROP TABLE IF EXISTS quick_responses;
DROP TABLE IF EXISTS ticket_worklogs;
DROP TABLE IF EXISTS ticket_observadores;
DROP TABLE IF EXISTS ticket_tags;
DROP TABLE IF EXISTS tags;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS bodegas;
DROP TABLE IF EXISTS status_history;
DROP TABLE IF EXISTS comments;
DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS users;

-- Las columnas deben coincidir con las entidades JPA (paquete entity) para usar ddl-auto: validate.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- [P4] Cuenta activa: un usuario desactivado no puede iniciar sesión ni usar su token
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    -- [P5] Intentos fallidos de login seguidos y hasta cuándo está bloqueada la cuenta
    failed_login_attempts INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role  CHECK (role IN ('ADMIN', 'TECHNICIAN', 'USER'))
);

CREATE TABLE tickets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(150)  NOT NULL,
    description    VARCHAR(2000) NOT NULL,
    category       VARCHAR(20)   NOT NULL,
    priority       VARCHAR(20)   NOT NULL,
    status         VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    requester_id   BIGINT        NOT NULL,
    technician_id  BIGINT,
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- [T2] Cuántas veces el solicitante reabrió el ticket
    reaperturas_count INT        NOT NULL DEFAULT 0,
    -- [P7] Fecha límite (SLA) según la prioridad. Nullable: los INSERT directos de data.sql la calculan aparte
    fecha_limite   TIMESTAMP,
    -- [P6] Ticket original del que este es duplicado (relación de la tabla consigo misma)
    duplicado_de_id BIGINT,
    CONSTRAINT fk_tickets_requester  FOREIGN KEY (requester_id)  REFERENCES users (id),
    -- SET NULL: si se borra el original, el duplicado se queda sin referencia en vez de impedir el borrado
    CONSTRAINT fk_tickets_duplicado_de FOREIGN KEY (duplicado_de_id) REFERENCES tickets (id) ON DELETE SET NULL,
    CONSTRAINT ck_tickets_reaperturas CHECK (reaperturas_count >= 0),
    CONSTRAINT fk_tickets_technician FOREIGN KEY (technician_id) REFERENCES users (id),
    CONSTRAINT ck_tickets_category CHECK (category IN ('HARDWARE', 'SOFTWARE', 'NETWORK', 'ACCESS', 'OTHER')),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_tickets_status   CHECK (status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'))
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT        NOT NULL,
    author_id   BIGINT        NOT NULL,
    content     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE status_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT      NOT NULL,
    previous_status  VARCHAR(20),
    new_status       VARCHAR(20) NOT NULL,
    changed_by_id    BIGINT      NOT NULL,
    changed_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- [T2][T3][P4][P6] Motivo del cambio cuando no es un paso normal del ciclo (reapertura, transferencia...)
    reason           VARCHAR(500),
    CONSTRAINT fk_status_history_ticket    FOREIGN KEY (ticket_id)     REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT fk_status_history_changed_by FOREIGN KEY (changed_by_id) REFERENCES users (id),
    CONSTRAINT ck_status_history_previous CHECK (previous_status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_status_history_new      CHECK (new_status      IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'))
);

-- Índices para las consultas frecuentes: listados por rol, comentarios e historial de un ticket.
CREATE INDEX idx_tickets_requester      ON tickets (requester_id);
CREATE INDEX idx_tickets_technician     ON tickets (technician_id);
CREATE INDEX idx_tickets_status         ON tickets (status);
CREATE INDEX idx_comments_ticket        ON comments (ticket_id);
CREATE INDEX idx_status_history_ticket  ON status_history (ticket_id);

-- Módulo de Inventario: Gestión de Bodegas y Productos
CREATE TABLE bodegas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(100) NOT NULL,
    ubicacion  VARCHAR(150) NOT NULL
);

CREATE TABLE productos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(100) NOT NULL,
    stock      INT          NOT NULL DEFAULT 0,
    bodega_id  BIGINT       NOT NULL,
    -- [P1] Bloqueo optimista (@Version): Hibernate lo incrementa en cada UPDATE
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_productos_bodega FOREIGN KEY (bodega_id) REFERENCES bodegas (id) ON DELETE CASCADE,
    CONSTRAINT ck_productos_stock CHECK (stock >= 0)
);

CREATE INDEX idx_productos_bodega ON productos (bodega_id);

-- =============================================================
-- Ejercicios de estudio (docs/estudio-examen.md)
-- Las FK hacia tickets llevan ON DELETE CASCADE: las pruebas borran con "DELETE FROM Ticket" (JPQL masivo),
-- que no pasa por las relaciones JPA y deja el trabajo a la base.
-- =============================================================

-- [T1] Etiquetas y tabla intermedia del @ManyToMany (sin columnas extra: solo las dos FK)
CREATE TABLE tags (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL,
    CONSTRAINT uk_tags_nombre UNIQUE (nombre)
);

CREATE TABLE ticket_tags (
    ticket_id  BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    PRIMARY KEY (ticket_id, tag_id),
    CONSTRAINT fk_ticket_tags_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT fk_ticket_tags_tag    FOREIGN KEY (tag_id)    REFERENCES tags (id)    ON DELETE CASCADE
);

-- [P8] Observadores: otro @ManyToMany, esta vez entre tickets y users
CREATE TABLE ticket_observadores (
    ticket_id  BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    PRIMARY KEY (ticket_id, user_id),
    CONSTRAINT fk_ticket_observadores_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT fk_ticket_observadores_user   FOREIGN KEY (user_id)   REFERENCES users (id)   ON DELETE CASCADE
);

-- [T4] Bitácora de tiempo: minutos entre 5 y 480 también en la base (defensa en profundidad)
CREATE TABLE ticket_worklogs (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id              BIGINT       NOT NULL,
    tecnico_id             BIGINT       NOT NULL,
    minutos_dedicados      INT          NOT NULL,
    descripcion_actividad  VARCHAR(500) NOT NULL,
    fecha_registro         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_worklogs_ticket  FOREIGN KEY (ticket_id)  REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT fk_worklogs_tecnico FOREIGN KEY (tecnico_id) REFERENCES users (id),
    CONSTRAINT ck_worklogs_minutos CHECK (minutos_dedicados BETWEEN 5 AND 480)
);

-- [T5] Plantillas: el título es único POR TÉCNICO (UNIQUE compuesto), no en toda la tabla
CREATE TABLE quick_responses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tecnico_id  BIGINT        NOT NULL,
    titulo      VARCHAR(100)  NOT NULL,
    contenido   VARCHAR(1000) NOT NULL,
    categoria   VARCHAR(20)   NOT NULL,
    CONSTRAINT fk_quick_responses_tecnico FOREIGN KEY (tecnico_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_quick_responses_tecnico_titulo UNIQUE (tecnico_id, titulo),
    CONSTRAINT ck_quick_responses_categoria CHECK (categoria IN ('HARDWARE', 'SOFTWARE', 'NETWORK', 'ACCESS', 'OTHER'))
);

-- [P2] Valoración: @OneToOne con tickets. El UNIQUE en ticket_id es lo que lo hace "uno a uno" en la base
CREATE TABLE valoraciones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT       NOT NULL,
    puntuacion  INT          NOT NULL,
    comentario  VARCHAR(500),
    fecha       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_valoraciones_ticket UNIQUE (ticket_id),
    CONSTRAINT fk_valoraciones_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE CASCADE,
    CONSTRAINT ck_valoraciones_puntuacion CHECK (puntuacion BETWEEN 1 AND 5)
);

-- [P1] Repuestos usados: entidad intermedia entre tickets y productos CON un campo extra (cantidad),
-- por eso no puede ser un @ManyToMany simple
CREATE TABLE ticket_repuestos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id       BIGINT    NOT NULL,
    producto_id     BIGINT    NOT NULL,
    tecnico_id      BIGINT    NOT NULL,
    cantidad        INT       NOT NULL,
    fecha_registro  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_repuestos_ticket   FOREIGN KEY (ticket_id)   REFERENCES tickets (id)   ON DELETE CASCADE,
    CONSTRAINT fk_repuestos_producto FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT fk_repuestos_tecnico  FOREIGN KEY (tecnico_id)  REFERENCES users (id),
    CONSTRAINT ck_repuestos_cantidad CHECK (cantidad > 0)
);

CREATE INDEX idx_tickets_fecha_limite  ON tickets (fecha_limite);
CREATE INDEX idx_worklogs_ticket       ON ticket_worklogs (ticket_id);
CREATE INDEX idx_repuestos_ticket      ON ticket_repuestos (ticket_id);

